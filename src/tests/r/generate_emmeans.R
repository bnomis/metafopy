# Reference values for emmprep() + emmeans (reference grids, marginal means, contrasts, adjustments, back-transformation)
# on rma.uni, rma.mv, rma.glmm, rma.mh and rma.ls fits.
#
# Usage (from the repository root):  LC_ALL=C.UTF-8 Rscript src/tests/r/generate_emmeans.R

suppressPackageStartupMessages({
  library(metafor)
  library(emmeans)
  library(jsonlite)
})

out_dir <- "src/tests/reference/phase9"
dir.create(out_dir, showWarnings = FALSE, recursive = TRUE)

df <- function(d) {
  d <- as.data.frame(d)
  cols <- lapply(d, function(col) if (is.factor(col)) as.character(col) else unname(as.vector(col)))
  names(cols) <- NULL
  list(names = names(d), columns = cols)
}
S <- function(x, ...) df(summary(x, ...))
quiet <- function(expr) suppressMessages(suppressWarnings(expr))

out <- list()
add <- function(key, x, ...) out[[key]] <<- S(x, ...)

dat <- escalc(measure = "RR", ai = tpos, bi = tneg, ci = cpos, di = cneg, data = dat.bcg)
dat$lat <- ifelse(dat$ablat >= 33, "high", "low")

# one factor and a covariate, z and Knapp-Hartung tests
res <- rma(yi, vi, mods = ~alloc + ablat, data = dat)
g <- emmprep(res)
e <- emmeans(g, ~alloc)
add("uni_alloc", e, infer = TRUE)
add("uni_alloc_resp", e, infer = TRUE, type = "response")
add("uni_alloc_level90", e, infer = TRUE, level = 0.9)
add("uni_alloc_null", e, infer = TRUE, null = -0.5)
add("uni_alloc_bias", e, infer = TRUE, type = "response", bias.adjust = TRUE)
add("uni_pairs", pairs(e), infer = TRUE)
add("uni_pairs_resp", pairs(e), infer = TRUE, type = "response")
add("uni_pairs_bonferroni", pairs(e), infer = TRUE, adjust = "bonferroni")
add("uni_pairs_holm", pairs(e), infer = TRUE, adjust = "holm")
add("uni_pairs_hochberg", pairs(e), infer = TRUE, adjust = "hochberg")
add("uni_pairs_hommel", pairs(e), infer = TRUE, adjust = "hommel")
add("uni_pairs_BH", pairs(e), infer = TRUE, adjust = "BH")
add("uni_pairs_BY", pairs(e), infer = TRUE, adjust = "BY")
add("uni_pairs_sidak", pairs(e), infer = TRUE, adjust = "sidak")
add("uni_pairs_scheffe", pairs(e), infer = TRUE, adjust = "scheffe")
add("uni_pairs_none", pairs(e), infer = TRUE, adjust = "none")
add("uni_revpairs", pairs(e, reverse = TRUE), infer = TRUE)
add("uni_trt_ctrl", contrast(e, "trt.vs.ctrl"), infer = TRUE)
add("uni_trt_ctrl_ref2", contrast(e, "trt.vs.ctrl", ref = 2), infer = TRUE)
add("uni_trt_ctrlk", contrast(e, "trt.vs.ctrlk"), infer = TRUE)
add("uni_dunnett_resp", contrast(e, "dunnett"), infer = TRUE, type = "response")
add("uni_eff", contrast(e, "eff"), infer = TRUE)
add("uni_del_eff", contrast(e, "del.eff"), infer = TRUE)
add("uni_consec", contrast(e, "consec"), infer = TRUE, adjust = "bonferroni")
add("uni_poly", contrast(e, "poly"), infer = TRUE)
add("uni_identity", contrast(e, "identity"), infer = TRUE)
add("uni_custom", contrast(e, list(`rnd vs others` = c(-0.5, 1, -0.5), `alt vs sys` = c(1, 0, -1))), infer = TRUE)
add("uni_excl", contrast(e, "pairwise", exclude = 3), infer = TRUE)
add("uni_pairs_ci_bonf_resp", pairs(e), infer = TRUE, adjust = "bonferroni", type = "response")
set.seed(1)
add("uni_consec_mvt", contrast(e, "consec"), infer = TRUE)
set.seed(1)
add("uni_pairs_mvt", pairs(e), infer = TRUE, adjust = "mvt")

# covariate only (averaged over the factor), covariate values via 'at', by-groups
add("uni_ablat", emmeans(g, ~ablat), infer = TRUE)
add("uni_ablat_prop", emmeans(g, ~ablat, weights = "proportional"), infer = TRUE)
g_at <- emmprep(res, at = list(ablat = c(10, 30, 50)))
add("uni_at_by", emmeans(g_at, ~alloc | ablat), infer = TRUE)
add("uni_at_pairs_by", pairs(emmeans(g_at, ~alloc | ablat)), infer = TRUE)
add("uni_at_cov", emmeans(g_at, ~ablat), infer = TRUE)
add("uni_at_cov_by", emmeans(g_at, ~ablat | alloc), infer = TRUE)
add("uni_at_pairs_cov", pairs(emmeans(g_at, ~ablat)), infer = TRUE)
g_lev <- emmprep(res, at = list(alloc = c("random", "systematic")))
add("uni_at_levels", emmeans(g_lev, ~alloc), infer = TRUE)
add("uni_overall", emmeans(g, ~1), infer = TRUE)

resk <- rma(yi, vi, mods = ~alloc + ablat, data = dat, test = "knha")
ek <- emmeans(emmprep(resk), ~alloc)
add("knha_alloc", ek, infer = TRUE)
add("knha_pairs", pairs(ek), infer = TRUE)
add("knha_pairs_resp", pairs(ek), infer = TRUE, type = "response")
add("knha_trt_ctrl", contrast(ek, "trt.vs.ctrl"), infer = TRUE)
add("knha_alloc_bias", ek, infer = TRUE, type = "response", bias.adjust = TRUE)
rest <- rma(yi, vi, mods = ~alloc + ablat, data = dat, test = "t")
add("t_alloc", emmeans(emmprep(rest), ~alloc), infer = TRUE)

# covariate listed before the factor, quadratic term
res2 <- rma(yi, vi, mods = ~ablat + alloc, data = dat)
add("order_alloc", emmeans(emmprep(res2), ~alloc), infer = TRUE)
add("order_ablat", emmeans(emmprep(res2), ~ablat), infer = TRUE)
resq <- rma(yi, vi, mods = ~ablat + I(ablat^2), data = dat)
add("quad_ablat", emmeans(emmprep(resq, at = list(ablat = c(10, 30, 50))), ~ablat), infer = TRUE)
add("quad_mean", emmeans(emmprep(resq), ~ablat), infer = TRUE)

# two factors: weights, interaction, by-groups
res3 <- rma(yi, vi, mods = ~alloc + lat, data = dat)
g3 <- emmprep(res3)
for (w in c("equal", "proportional", "outer", "cells", "flat"))
  add(paste0("two_alloc_", w), emmeans(g3, ~alloc, weights = w), infer = TRUE)
add("two_lat", emmeans(g3, ~lat), infer = TRUE)
add("two_both", emmeans(g3, ~alloc * lat), infer = TRUE)
add("two_both_pairs", pairs(emmeans(g3, ~alloc * lat)), infer = TRUE)
add("two_by", emmeans(g3, ~alloc | lat), infer = TRUE)
add("two_by_pairs", pairs(emmeans(g3, ~alloc | lat)), infer = TRUE)
add("two_by_pairs_holm", pairs(emmeans(g3, ~alloc | lat)), infer = TRUE, adjust = "holm")
add("two_by_pairs_cross", pairs(emmeans(g3, ~alloc | lat)), infer = TRUE, adjust = "none", cross.adjust = "bonferroni")
add("two_lat_by_alloc_pairs", pairs(emmeans(g3, ~lat | alloc)), infer = TRUE)
add("two_numw", emmeans(g3, ~alloc, weights = c(1, 3)), infer = TRUE)
add("two_pairs_prop", pairs(emmeans(g3, ~alloc, weights = "proportional")), infer = TRUE)
add("two_contrast_by", contrast(emmeans(g3, ~alloc | lat), "trt.vs.ctrl"), infer = TRUE)
res4 <- rma(yi, vi, mods = ~alloc * lat, data = dat)
g4 <- emmprep(res4)
add("int_by", emmeans(g4, ~alloc | lat), infer = TRUE)
add("int_by_pairs", pairs(emmeans(g4, ~alloc | lat)), infer = TRUE)
add("int_both_pairs", pairs(emmeans(g4, ~alloc * lat)), infer = TRUE)
add("int_both_eff", contrast(emmeans(g4, ~alloc * lat), "eff"), infer = TRUE)
add("int_alloc", emmeans(g4, ~alloc), infer = TRUE)
add("int_alloc_prop", emmeans(g4, ~alloc, weights = "proportional"), infer = TRUE)
add("int_interaction", contrast(emmeans(g4, ~alloc * lat), interaction = c("pairwise", "pairwise")), infer = TRUE)
res5 <- rma(yi, vi, mods = ~alloc * ablat, data = dat)
g5 <- emmprep(res5, at = list(ablat = c(15, 40)))
add("slopes_by", emmeans(g5, ~alloc | ablat), infer = TRUE)
add("slopes_pairs", pairs(emmeans(g5, ~alloc | ablat)), infer = TRUE)

# regrid
add("regrid", regrid(e), infer = TRUE)
add("regrid_pairs", pairs(regrid(e)), infer = TRUE)
add("regrid_bias", regrid(e, bias.adjust = TRUE), infer = TRUE)

# estimator, weighted and unweighted fits
resfe <- rma(yi, vi, mods = ~alloc, data = dat, method = "FE")
add("fe_alloc", emmeans(emmprep(resfe), ~alloc), infer = TRUE, type = "response")
resdl <- rma(yi, vi, mods = ~alloc, data = dat, method = "DL", weighted = FALSE)
add("dl_alloc", emmeans(emmprep(resdl), ~alloc), infer = TRUE)
res0 <- rma(yi, vi, data = dat)
add("int_only", emmeans(emmprep(res0), ~1), infer = TRUE, type = "response")
add("int_only_bias", emmeans(emmprep(res0), ~1), infer = TRUE, type = "response", bias.adjust = TRUE)
add("df_override", emmeans(emmprep(res, df = 7), ~alloc), infer = TRUE)
add("sigma_override", emmeans(emmprep(res, sigma = 0.5), ~alloc), infer = TRUE, type = "response", bias.adjust = TRUE)
add("tran_override", emmeans(emmprep(res, tran = "sqrt"), ~alloc), infer = TRUE, type = "response")

# transformations by measure
dat_plo <- escalc(measure = "PLO", xi = tpos, ni = tpos + tneg, data = dat.bcg)
resplo <- rma(yi, vi, mods = ~alloc, data = dat_plo)
eplo <- emmeans(emmprep(resplo), ~alloc)
add("plo", eplo, infer = TRUE, type = "response")
add("plo_pairs", pairs(eplo), infer = TRUE, type = "response")
dat_pas <- escalc(measure = "PAS", xi = tpos, ni = tpos + tneg, data = dat.bcg)
add("pas", emmeans(emmprep(rma(yi, vi, mods = ~alloc, data = dat_pas)), ~alloc), infer = TRUE, type = "response")
dat_irs <- escalc(measure = "IRS", xi = tpos, ti = tpos + tneg + 10, data = dat.bcg)
add("irs", emmeans(emmprep(rma(yi, vi, mods = ~alloc, data = dat_irs)), ~alloc), infer = TRUE, type = "response")
dat_zcor <- escalc(measure = "ZCOR", ri = ri, ni = ni, data = dat.molloy2014)
reszcor <- rma(yi, vi, mods = ~design, data = dat_zcor)
ez <- emmeans(emmprep(reszcor), ~design)
add("zcor", ez, infer = TRUE, type = "response")
add("zcor_link", ez, infer = TRUE)
add("zcor_pairs", pairs(ez), infer = TRUE)
dat_ahw <- escalc(measure = "AHW", ai = ai, mi = mi, ni = ni, data = dat.bonett2010)
add("ahw", emmeans(emmprep(rma(yi, vi, mods = ~caregivers, data = dat_ahw)), ~caregivers), infer = TRUE, type = "response")
dat_abt <- escalc(measure = "ABT", ai = ai, mi = mi, ni = ni, data = dat.bonett2010)
add("abt", emmeans(emmprep(rma(yi, vi, mods = ~caregivers, data = dat_abt)), ~caregivers), infer = TRUE, type = "response")
dat_or <- escalc(measure = "OR", ai = tpos, bi = tneg, ci = cpos, di = cneg, data = dat.bcg)
resor <- rma(yi, vi, mods = ~alloc, data = dat_or)
add("or_ratio", pairs(emmeans(emmprep(resor), ~alloc)), infer = TRUE, type = "response")

# subset and missing values
dat_na <- dat
dat_na$ablat[3] <- NA
resna <- rma(yi, vi, mods = ~alloc + ablat, data = dat_na, subset = year > 1950)
add("subset_na", emmeans(emmprep(resna), ~alloc), infer = TRUE)
add("subset_na_pairs", pairs(emmeans(emmprep(resna), ~alloc)), infer = TRUE)

# rma.mv
dat_k <- dat.konstantopoulos2011
resmv <- rma.mv(yi, vi, mods = ~I(year - 1990), random = ~1 | district/school, data = dat_k)
add("mv_year", emmeans(emmprep(resmv, at = list(year = c(1975, 1990, 2005))), ~year), infer = TRUE)
resmv2 <- rma.mv(yi, vi, mods = ~I(year - 1990), random = ~1 | district/school, data = dat_k, test = "t")
add("mv_year_t", emmeans(emmprep(resmv2, at = list(year = c(1975, 1990, 2005))), ~year), infer = TRUE)
add("mv_year_t_pairs", pairs(emmeans(emmprep(resmv2, at = list(year = c(1975, 1990, 2005))), ~year)), infer = TRUE)
dat_b <- dat.berkey1998
V <- bldiag(lapply(split(dat_b[, c("v1i", "v2i")], dat_b$trial), as.matrix))
resun <- rma.mv(yi, V, mods = ~0 + outcome, random = ~outcome | trial, struct = "UN", data = dat_b)
eun <- emmeans(emmprep(resun), ~outcome)
add("mv_un", eun, infer = TRUE)
add("mv_un_pairs", pairs(eun), infer = TRUE)
resun2 <- rma.mv(yi, V, mods = ~outcome, random = ~outcome | trial, struct = "UN", data = dat_b)
add("mv_un_treat", emmeans(emmprep(resun2), ~outcome), infer = TRUE)
resunk <- rma.mv(yi, V, mods = ~0 + outcome, random = ~outcome | trial, struct = "UN", data = dat_b, test = "t")
add("mv_un_t", emmeans(emmprep(resunk), ~outcome), infer = TRUE)

# rma.glmm and rma.ls (emmprep gives NA for rma.mh and rma.peto fits, whose coefficient has no name, and fails for selmodel fits)
resgl <- quiet(rma.glmm(measure = "OR", ai = tpos, bi = tneg, ci = cpos, di = cneg, data = dat.bcg, mods = ~alloc))
egl <- emmeans(emmprep(resgl), ~alloc)
add("glmm", egl, infer = TRUE)
add("glmm_resp", egl, infer = TRUE, type = "response")
add("glmm_pairs", pairs(egl), infer = TRUE)
resls <- rma(yi, vi, mods = ~alloc, scale = ~ablat, data = dat)
els <- emmeans(emmprep(resls), ~alloc)
add("ls", els, infer = TRUE)
add("ls_pairs", pairs(els), infer = TRUE)
add("ls_resp", els, infer = TRUE, type = "response")

# robust
resrob <- robust(res, cluster = trial)
add("robust", emmeans(emmprep(resrob), ~alloc), infer = TRUE)

write(toJSON(out, auto_unbox = TRUE, digits = NA, na = "null", null = "null"), file.path(out_dir, "emmeans.json"))
cat("wrote", length(out), "cases\n")
